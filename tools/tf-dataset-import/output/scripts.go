package output

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// WriteRollbackScript emits `terraform state rm` for whatever this run actually imported, so it
// removes only that from state without touching the Observe datasets themselves.
//
// Scoped to Entry.NeedsDatasetImport / NeedsGrantsImport rather than every entry: an already-managed
// dataset or grants resource was not freshly imported by this run, and removing it from state would
// undo work this run had nothing to do with.
func WriteRollbackScript(path string, m *Manifest) error {
	var b strings.Builder

	b.WriteString("#!/usr/bin/env bash\n")
	b.WriteString("# Generated by tf-dataset-import. Removes what this run imported from terraform\n")
	b.WriteString("# state. The Observe datasets are left untouched.\n")
	b.WriteString("set -euo pipefail\n\n")

	fmt.Fprintf(&b, "MODULE_DIR=%q\n\n", m.ModuleDir)
	b.WriteString("test -d \"$MODULE_DIR\" || {\n")
	b.WriteString("  echo \"run this from the account repo root ($MODULE_DIR not found here)\" >&2\n")
	b.WriteString("  exit 1\n")
	b.WriteString("}\n\n")
	if m.TFWorkspace != "" {
		fmt.Fprintf(&b, "WORKSPACE=%q\n", m.TFWorkspace)
		b.WriteString("terraform workspace select \"$WORKSPACE\"\n")
		b.WriteString("test \"$(terraform workspace show)\" = \"$WORKSPACE\"\n\n")
	}

	for i := len(m.Entries) - 1; i >= 0; i-- {
		e := m.Entries[i]
		// Remove grants before the dataset: removing the dataset first would leave a dangling
		// resource_grants entry referencing a resource that no longer exists in state.
		if e.NeedsGrantsImport() {
			fmt.Fprintf(&b, "terraform state rm '%s.observe_resource_grants.%s' || true\n", m.ModuleAddress, e.ResourceName)
		}
		if e.NeedsDatasetImport() {
			fmt.Fprintf(&b, "terraform state rm '%s' || true\n", e.ImportAddress)
		}
	}
	return writeExecutable(path, b.String())
}

func writeExecutable(path, content string) error {
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	return os.WriteFile(path, []byte(content), 0o755)
}
